// book.issacharson.com: branded booking links (lead-desk#184).
//
// Each page here forwards to the matching fixed link in lead-desk, which in
// turn forwards to the current Google Calendar booking page listed in
// lead-desk's booking-pages.json. So this site never changes when a booking
// page is replaced: only booking-pages.json in lead-desk does.
//
//   https://book.issacharson.com/carematchr/
//     -> https://issacharson.github.io/lead-desk/book/carematchr/
//     -> the CareMatchr demo booking page on file
//
// `node scripts/build.mjs` writes the pages; `--check` fails if they differ.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
export const TARGET_BASE = "https://issacharson.github.io/lead-desk/book/";

export const LINKS = [
  { name: "carematchr", title: "CareMatchr demo" },
  { name: "carematchr-dbs", title: "CareMatchr DBS demo" },
  { name: "privacy-a-to-z", title: "Privacy A to Z readiness check" },
];

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

export function forwardPage({ name, title }) {
  const url = `${TARGET_BASE}${name}/`;
  return `<!doctype html>
<html lang="en-GB">
<head>
<!-- Generated by scripts/build.mjs. Forwards to lead-desk's fixed link, which forwards to the booking page on file (lead-desk#184). -->
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<meta http-equiv="refresh" content="0; url=${url}">
<title>Book: ${esc(title)}</title>
<script>location.replace(${JSON.stringify(url)});</script>
<style>body{font-family:Arial,Helvetica,sans-serif;color:#1b2440;margin:48px 24px;line-height:1.5}a{color:#2f4a9a}</style>
</head>
<body>
<p>Opening the booking page for <strong>${esc(title)}</strong>…</p>
<p>If nothing happens, <a href="${url}">open the booking page</a>.</p>
</body>
</html>
`;
}

export function indexPage() {
  const items = LINKS.map((l) => `<li><a href="/${l.name}/">${esc(l.title)}</a></li>`).join("\n");
  return `<!doctype html>
<html lang="en-GB">
<head>
<!-- Generated by scripts/build.mjs. -->
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>Book a session with Issac Harson</title>
<style>body{font-family:Arial,Helvetica,sans-serif;color:#1b2440;margin:48px 24px;line-height:1.5;max-width:40em}a{color:#2f4a9a}</style>
</head>
<body>
<h1>Book a session with Issac Harson</h1>
<ul>
${items}
</ul>
<p>Or visit <a href="https://issacharson.com">issacharson.com</a>.</p>
</body>
</html>
`;
}

export function files() {
  const out = { "index.html": indexPage(), "404.html": indexPage(), "CNAME": "book.issacharson.com\n", ".nojekyll": "" };
  for (const l of LINKS) out[`${l.name}/index.html`] = forwardPage(l);
  return out;
}

const SITE = path.join(root, "site");

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const want = files();
  if (process.argv.includes("--check")) {
    const bad = Object.entries(want).filter(([f, c]) => !fs.existsSync(path.join(SITE, f)) || fs.readFileSync(path.join(SITE, f), "utf8") !== c).map(([f]) => f);
    const extra = fs.existsSync(SITE) ? fs.readdirSync(SITE, { recursive: true }).filter((f) => !fs.statSync(path.join(SITE, f)).isDirectory() && !(f in want)) : [];
    if (bad.length || extra.length) {
      console.error(`site/ is out of date: ${[...bad, ...extra].join(", ")}. Run node scripts/build.mjs and commit site/.`);
      process.exit(1);
    }
    console.log("site/ matches scripts/build.mjs.");
  } else {
    fs.rmSync(SITE, { recursive: true, force: true });
    for (const [f, c] of Object.entries(want)) {
      fs.mkdirSync(path.dirname(path.join(SITE, f)), { recursive: true });
      fs.writeFileSync(path.join(SITE, f), c);
      console.log(`wrote site/${f}`);
    }
  }
}
